"""Fail a release if its educational holdout evaluation regresses."""

import json
import math

from advanced_regression_mlops.config import FEATURES, METRICS_PATH

MIN_R2 = 0.80
MAX_MAE = 3.0
MAX_RMSE = 4.0


def verify_release_quality(metrics: dict) -> dict[str, float]:
    """Require valid schema, finite metrics and clear improvement over baselines."""
    if metrics.get("dataset") != "OpenML 531 (historical Boston Housing)":
        raise ValueError("Unexpected dataset")
    if metrics.get("features") != list(FEATURES) or "B" in metrics["features"]:
        raise ValueError("Unexpected input schema")
    if metrics.get("n_rows") != 506 or metrics.get("n_train") != 404:
        raise ValueError("Unexpected training data size")
    if metrics.get("n_test") != 102:
        raise ValueError("Unexpected test data size")

    holdout = metrics.get("holdout", {})
    for key in ("r2", "mae", "rmse"):
        value = holdout.get(key)
        if not isinstance(value, (float, int)) or not math.isfinite(value):
            raise ValueError(f"Missing or non-finite holdout metric: {key}")

    if holdout["r2"] < MIN_R2 or holdout["mae"] > MAX_MAE or holdout["rmse"] > MAX_RMSE:
        raise ValueError(f"Holdout quality gate failed: {holdout}")

    for name in ("dummy_mean", "ridge"):
        baseline = metrics.get("baselines", {}).get(name, {})
        for key in ("mae", "rmse"):
            other = baseline.get(key)
            if not isinstance(other, (float, int)) or not math.isfinite(other):
                raise ValueError(f"Missing or invalid {name} {key}")
            if holdout[key] >= other:
                raise ValueError(f"Release model must beat {name} on {key}")

    return {key: float(holdout[key]) for key in ("mae", "rmse", "r2")}


def main() -> None:
    """Check the metrics generated by the one CI training run."""
    metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    print("RELEASE QUALITY PASSED:", verify_release_quality(metrics))


if __name__ == "__main__":
    main()
